class TimeSeriesStore:
    """Time series database for metrics"""
    
    def __init__(self):
        self.points = []
        logger.info("✅ Time Series Store initialized (in-memory)")
    
    async def write_points(self, points: List[Dict]):
        """Write time series points"""
        for point in points:
            self.points.append({
                **point,
                "stored_at": datetime.utcnow().isoformat()
            })
    
    async def query(self, query: str) -> Dict[str, Any]:
        """Query time series data"""
        
        # Simple in-memory query simulation
        results = {
            "execution_count": len([p for p in self.points if p.get("measurement") == "execution"]),
            "task_count": len([p for p in self.points if p.get("measurement") == "task_execution"])
        }
        
        return results